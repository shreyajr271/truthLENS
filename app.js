  // Process live uploaded user file
  async handleUploadedFile(file, modality) {
    if (!window.crypto || !crypto.subtle) {
      this.showToast('SHA-256 hashing requires a secure local server. Open this page with VS Code Live Server or localhost.', 'warning');
      return;
    }

    let hashBuffer;
    try {
      const arrayBuffer = await file.arrayBuffer();
      hashBuffer = await crypto.subtle.digest('SHA-256', arrayBuffer);
    } catch (error) {
      this.showToast(`Could not read or hash ${file.name}. Please try another file.`, 'warning');
      return;
    }
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    const sha256 = hashArray.map(b => b.toString(16).padStart(2, '0')).join('');

    const activeCase = this.cases[this.currentCaseId];
    const mediaData = {
      filename: file.name,
      size: `${(file.size / 1024 / 1024).toFixed(2)} MB`,
      mime: file.type || 'Unknown file type',
      hash: sha256
    };
    Object.assign(activeCase[modality], mediaData);
    const addedFiles = ['image', 'video', 'audio', 'text']
      .filter(type => activeCase[type].filename)
      .map(type => activeCase[type].filename);
    activeCase.classification = 'EVIDENCE ADDED';
    activeCase.crossModalStatus = 'Evidence added; not analyzed';
    activeCase.summary = `${addedFiles.length} file${addedFiles.length === 1 ? '' : 's'} added. SHA-256 hashes are recorded. No automated verdict has been generated.`;
    document.getElementById('case-threat-tag').textContent = activeCase.classification;
    document.getElementById('case-description').textContent = activeCase.summary;
    document.getElementById('triage-cross-modal-status').textContent = activeCase.crossModalStatus;
    this.updateIngestCard(`${modality}-drop`, activeCase[modality]);

    if (modality === 'image') {
      const reader = new FileReader();
      reader.onload = (e) => {
        const img = new Image();
        img.onload = () => {
          this.caseImages[this.currentCaseId] = img;
          this.customEvidence.image = img;
          this.renderCustomImageForensics(img);
        };
        img.src = e.target.result;
      };
      reader.readAsDataURL(file);
    } else if (modality === 'text') {
      const text = await file.text();
      this.customEvidence.text = text;
      activeCase.text.rawText = text;
      this.renderTextForensics();
    }

    this.updateChainOfCustodyUI();
    this.showToast(`Added ${file.name}. SHA-256 recorded; automated analysis is not available for every file type.`, 'success');
  },

