  updateIngestCard(cardId, mediaData) {
    const card = document.getElementById(cardId);
    if (!card) return;

    const empty = !mediaData || !mediaData.filename;
    card.classList.toggle('has-file', !empty);
    const title = card.querySelector('.drop-title');
    const meta = card.querySelector('.drop-meta');
    const hash = card.querySelector('.hash-preview');
    const pill = card.querySelector('.drop-status-pill');

    if (title) title.textContent = empty ? 'No file selected' : mediaData.filename;
    if (meta) meta.textContent = empty ? 'Choose a file or drop it here' : `${mediaData.size} • ${mediaData.mime}`;
    if (hash) hash.textContent = empty ? 'SHA-256: not available' : `SHA: ${mediaData.hash ? mediaData.hash.substring(0, 14) + '...' : 'N/A'}`;
    if (pill) {
      pill.textContent = empty ? 'EMPTY' : 'HASHED';
      pill.classList.toggle('loaded', !empty);
    }
  },

